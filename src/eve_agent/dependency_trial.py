"""Experimental provenance dependencies: review candidates, never automatic truth changes."""
from copy import deepcopy

REVIEW_TASK = (
    'Review the listed memories in light of the new observation and their original sources. '
    'Return updates only where needed and list the IDs you reviewed. '
    'Relationships and conclusions are your judgments. A dependency only explains how a thought arose; '
    'it does not mean it must become false when a premise changes. Consider other support. '
    'Maintain uncertainty and provenance. Write in the language of the memories.'
)
RECALL_TASK = (
    'Answer the question using the supplied experimental memories and their receipts. '
    'Distinguish what the sources state from interpretations and unresolved uncertainty. '
    'Return answer and the IDs of memories used. Do not invent facts.'
)


def review_candidates(records, changed):
    """Directed transitive dependency closure; no word matching or semantic decisions."""
    by_id = {r['id']: r for r in records}
    if len(by_id) != len(records) or not set(changed) <= by_id.keys():
        raise ValueError('invalid_dependency_identity')
    if any(not set(r['depends_on']) <= by_id.keys() for r in records):
        raise ValueError('unknown_dependency')
    affected = set(changed)
    while True:
        expanded = affected | {r['id'] for r in records if set(r['depends_on']) & affected}
        if expanded == affected:
            return [r['id'] for r in records if r['id'] in affected]
        affected = expanded


def patch_schema(review_ids, record_ids, source_ids):
    return {'type': 'object', 'additionalProperties': False, 'required': ['reviewed_ids','updates'],
            'properties': {
                'reviewed_ids': {'type': 'array','items': {'type':'string','enum':review_ids}},
                'updates': {'type':'array','items': {
                    'type':'object','additionalProperties':False,
                    'required':['id','text','uncertainty','evidence','depends_on'],
                    'properties': {
                        'id':{'type':'string','enum':review_ids},
                        'text':{'type':'string'},'uncertainty':{'type':'string'},
                        'evidence':{'type':'array','minItems':1,'items':{'type':'string','enum':source_ids}},
                        'depends_on':{'type':'array','items':{'type':'string','enum':record_ids}}}}}}}


def apply_review(records, patch, review_ids, sources):
    from jsonschema import Draft202012Validator
    ids=[r['id'] for r in records]
    Draft202012Validator(patch_schema(review_ids,ids,[s['id'] for s in sources])).validate(patch)
    if set(patch['reviewed_ids']) != set(review_ids):
        raise ValueError('review_incomplete')
    changes={r['id']:r for r in patch['updates']}
    if len(changes)!=len(patch['updates']):
        raise ValueError('duplicate_update')
    # Unaffected records are copied unchanged, not regenerated by the model.
    result=[deepcopy(changes.get(r['id'],r)) for r in records]
    review_candidates(result,[])
    return result


LEARN_TASK = (
    'Form memories from these source observations. Write readable thoughts, cite their sources, '
    'and identify which of your thoughts depend on which other thoughts. '
    'Relationship meaning and uncertainty are your judgments. Original statements and interpretations '
    'need not have the same evidential status. Do not assume an assistant hypothesis is established. '
    'Return memories in the language of the sources.'
)


def learning_schema(source_ids):
    record = patch_schema(['placeholder'], ['placeholder'], source_ids)['properties']['updates']['items']
    from copy import deepcopy
    record = deepcopy(record)
    record['properties']['id'] = {'type': 'string'}
    record['properties']['depends_on'] = {'type': 'array', 'items': {'type': 'string'}}
    return {'type':'object','additionalProperties':False,'required':['memories'],
            'properties':{'memories':{'type':'array','items':record}}}


def validate_learned(records, sources):
    from jsonschema import Draft202012Validator
    Draft202012Validator(learning_schema([s['id'] for s in sources])).validate({'memories': records})
    if not records or any(not r['id'].strip() for r in records):
        raise ValueError('nonempty_memories_required')
    review_candidates(records, [])
    return deepcopy(records)
